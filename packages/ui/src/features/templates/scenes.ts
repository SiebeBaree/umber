import type { Platform, Slot } from './platforms'

/**
 * The scene deck: every photo Templates can plan, written out by hand.
 *
 * The prompt is the whole scene as the model will read it, minus the identity
 * and realism paragraphs that `compose-prompt` wraps around every one. It is
 * what the user reviews and edits, so it is plain prose with no hidden parts.
 *
 * The tags exist for the picker. A set never repeats a place, a light or a
 * framing while the deck still has something else, which is what keeps ten
 * photos from looking like one afternoon.
 *
 * Prompts describe clothes, pose, place and camera, never the person: their
 * face and body come from their own photos. They say "they" because nothing
 * here knows who the person is.
 */

export type Place =
    | 'street'
    | 'nature'
    | 'home'
    | 'cafe'
    | 'restaurant'
    | 'shop'
    | 'water'
    | 'venue'
    | 'transit'
    | 'work'
    | 'rooftop'

export type Light =
    | 'overcast'
    | 'harsh-sun'
    | 'window'
    | 'mixed-indoor'
    | 'fluorescent'
    | 'night-flash'
    | 'dusk'

export type Framing = 'face' | 'half' | 'full' | 'wide'

/** Who is holding the camera, which decides the angle and how posed it looks. */
export type ShotBy = 'friend' | 'self-timer' | 'selfie'

export interface SceneCard {
    /** Stable across releases: recent sets are remembered by it. */
    readonly id: string
    /** Shown under the photo. */
    readonly title: string
    readonly platforms: readonly Platform[]
    readonly slot: Slot
    readonly place: Place
    readonly light: Light
    readonly framing: Framing
    readonly shotBy: ShotBy
    readonly prompt: string
}

